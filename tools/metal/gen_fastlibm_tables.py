def split(d):
    h = np.float32(d)
    lo = np.float32(d - float(h))
    return float(h), float(lo)


def fl(x):
    return f"{np.float32(x).item().hex()}f" if x else "0.0f"


def table(name, values):
    hs, ls = zip(*(split(v) for v in values))
    return (f"constant float {name}_H[{len(values)}] = {{{', '.join(fl(h) for h in hs)}}};\n"
            f"constant float {name}_L[{len(values)}] = {{{', '.join(fl(lo) for lo in ls)}}};\n")


def const(name, d):
    h, lo = split(d)
    return f"#define {name}_H {fl(h)}\n#define {name}_L {fl(lo)}\n"


POWF_LOG2C_BITS = [int(h, 16) for h in """BFDEFEC65B963019 BFDB0B6832D4FCA4 BFD7418B0A1FB77B BFD39DE91A6DCF7B
 BFD01D9BF3F2B631 BFC97C1D1B3B7AF0 BFC2F9E393AF3C9F BFB960CBBF788D5C BFAA6F9DB6475FCE 0000000000000000
 3FB338CA9F24F53D 3FC476A9543891BA 3FCE840B4AC4E4D2 3FD40645F0C6651C 3FD88E9C2C1B9FF8 3FDCE0A44EB17BCC""".split()]
POWF_LOG2_POLY_BITS = [int(h, 16) for h in "3FD27616C9496E0B BFD71969A075C67A 3FDEC70A6CA7BADD BFE7154748BEF6C8 3FF71547652AB82B".split()]
EXP2F_POLY_BITS = [int(h, 16) for h in "3FAC6AF84B912394 3FCEBFCE50FAC4F3 3FE62E42FF0C52D6".split()]


def d(b):
    return struct.unpack("<d", struct.pack("<Q", b))[0]


exp2f = [struct.unpack("<d", struct.pack("<Q", b))[0] for b in EXP2F_TAB_BITS]
# glibc's tables store T[i] with the 2^(i/32) exponent bias removed: T[i] = 2^(i/32) * 2^(-i/32 * 52 ...)
# -- the bits are (2^(i/32) bits) - (i << 47); restore the real 2^(i/32) value.
exp2f_val = [struct.unpack("<d", struct.pack("<Q", b + (i << 47)))[0] for i, b in enumerate(EXP2F_TAB_BITS)]
HDR = "// generated by tools/metal/gen_fastlibm_tables.py; do not edit\n#pragma once\n"
ln2 = float.fromhex("0x1.62e42fefa39efp-1")
l1 = round(ln2 * 2**15) / 2**15          # 15 significant bits
l2 = round((ln2 - l1) * 2**34) / 2**34   # 15 significant bits
l3 = ln2 - l1 - l2
assert l1 == np.float32(l1) and l2 == np.float32(l2)
for piece in (l1, l2):                   # k * piece exact in binary32 for |k| < 256
    m, e = __import__("math").frexp(piece)
    assert (m * 2**15).is_integer(), piece
files = {
    "logf": [table("ARWEN_LOGF_INVC", LOGF_INVC), table("ARWEN_LOGF_LOGC", LOGF_LOGC),
             const("ARWEN_LOGF_A0", float.fromhex("-0x1.00ea348b88334p-2")),
             const("ARWEN_LOGF_A1", float.fromhex("0x1.5575b0be00b6ap-2")),
             const("ARWEN_LOGF_A2", float.fromhex("-0x1.ffffef20a4123p-2")),
             f"#define ARWEN_LN2_1 {fl(l1)}\n#define ARWEN_LN2_2 {fl(l2)}\n#define ARWEN_LN2_3 {fl(l3)}\n"],
    "expf": [table("ARWEN_EXP2F_T", exp2f_val),
             const("ARWEN_EXPF_INVLN2N", float.fromhex("0x1.71547652b82fep+0") * 32.0),
             const("ARWEN_EXPF_C0", float.fromhex("0x1.c6af84b912394p-5") / 32.0 / 32.0 / 32.0),
             const("ARWEN_EXPF_C1", float.fromhex("0x1.ebfce50fac4f3p-3") / 32.0 / 32.0),
             const("ARWEN_EXPF_C2", float.fromhex("0x1.62e42ff0c52d6p-1") / 32.0)],
    "powf": [table("ARWEN_POWF_LOG2C", [d(b) for b in POWF_LOG2C_BITS])]
            + [const(f"ARWEN_POWF_A{i}", d(b)) for i, b in enumerate(POWF_LOG2_POLY_BITS)]
            + [const(f"ARWEN_EXP2F_C{i}", d(b)) for i, b in enumerate(EXP2F_POLY_BITS)],
}
outdir = Path(sys.argv[1])
for fam, parts in files.items():
    (outdir / f"arwen_fastlibm_tables_{fam}.h").write_text(HDR + "".join(parts))
